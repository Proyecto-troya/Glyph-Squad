export const TEXTS: Record<Lang, Record<TextKey, string>> = { es, quz, en };

/** Texto en el idioma pedido, con cada {nombre} sustituido por su valor. */
export function translate(lang: Lang, key: TextKey, values: Record<string, string | number> = {}): string {
  return TEXTS[lang][key].replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ""));
}
